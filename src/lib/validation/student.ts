import { z } from "zod";
import { NG_PHONE_MESSAGE, NG_PHONE_REGEX } from "@/lib/validation/common";
import { GUARDIAN_RELATIONSHIPS } from "@/types/guardians";
import { GENDERS, STUDENT_STATUSES } from "@/types/students";

export const BLOOD_GROUP_OPTIONS = ["A+", "A-", "B+", "B-", "AB+", "AB-", "O+", "O-"] as const;
export const GENOTYPE_OPTIONS = ["AA", "AS", "SS", "AC", "SC"] as const;

const name = (label: string) => z.string().trim().min(1, `${label} is required`).max(80, "Keep it under 80 characters");
const optionalText = (max: number) => z.string().trim().max(max, `Keep it under ${max} characters`);
const optionalPhone = z
  .string()
  .trim()
  .refine((v) => v === "" || NG_PHONE_REGEX.test(v), NG_PHONE_MESSAGE);
const requiredPhone = z.string().trim().refine((v) => NG_PHONE_REGEX.test(v), NG_PHONE_MESSAGE);
const optionalEmail = z
  .string()
  .trim()
  .refine((v) => v === "" || z.email().safeParse(v).success, "Enter a valid email address");

/** Student profile fields shared by Add and Edit (mirrors StudentProfileFields in student.dto.ts). */
const studentFields = {
  firstName: name("First name"),
  lastName: name("Last name"),
  middleName: optionalText(80),
  gender: z.enum(GENDERS, { error: "Select a gender" }),
  dateOfBirth: z.string().min(1, "Date of birth is required"),
  nationality: optionalText(80),
  stateOfOrigin: z.string().min(1, "State of origin is required"),
  lga: optionalText(80),
  religion: optionalText(80),
  email: optionalEmail,
  phone: optionalPhone,
  addressLine: optionalText(255),
  bloodGroup: z.string(), // "" = unknown
  genotype: z.string(), // "" = unknown
  classArmId: z.string(), // "" = not placed yet
  admissionDate: z.string().min(1, "Admission date is required"),
};

/**
 * "New Admission". Session and Term are gone (the backend places a student by arm and
 * admission date). Allergies and emergency contact have no backend field, so they're
 * saved into the student's notes. The guardian is either new or an existing record.
 */
export const addStudentSchema = z
  .object({
    ...studentFields,
    studentId: optionalText(40), // admission number; generated by the backend when empty
    allergies: optionalText(500),
    emergencyContactName: optionalText(80),
    emergencyPhone: optionalPhone,
    // "none": the user can't link guardians (no guardians.update); someone else adds them later.
    guardianMode: z.enum(["new", "existing", "none"]),
    existingGuardianId: z.string(),
    guardianFirstName: z.string().trim().max(80),
    guardianLastName: z.string().trim().max(80),
    relationship: z.union([z.enum(GUARDIAN_RELATIONSHIPS), z.literal("")]),
    guardianPhone: z.string().trim(),
    guardianEmail: optionalEmail,
    guardianAddress: z.string().trim().max(255),
  })
  .superRefine((v, ctx) => {
    if (v.guardianMode === "none") return;
    if (!v.relationship) ctx.addIssue({ code: "custom", path: ["relationship"], message: "Select a relationship" });
    if (v.guardianMode === "existing") {
      if (!v.existingGuardianId) ctx.addIssue({ code: "custom", path: ["existingGuardianId"], message: "Choose a guardian" });
      return;
    }
    if (!v.guardianFirstName) ctx.addIssue({ code: "custom", path: ["guardianFirstName"], message: "First name is required" });
    if (!v.guardianLastName) ctx.addIssue({ code: "custom", path: ["guardianLastName"], message: "Last name is required" });
    if (!NG_PHONE_REGEX.test(v.guardianPhone)) ctx.addIssue({ code: "custom", path: ["guardianPhone"], message: NG_PHONE_MESSAGE });
    if (!v.guardianAddress) ctx.addIssue({ code: "custom", path: ["guardianAddress"], message: "Residential address is required" });
  });

export type AddStudentValues = z.infer<typeof addStudentSchema>;

/** "Edit Student": every field UpdateStudentDto accepts. Guardians and status are managed on the profile. */
export const editStudentSchema = z.object({
  ...studentFields,
  notes: optionalText(2000),
});

export type EditStudentValues = z.infer<typeof editStudentSchema>;

/** Add/Edit Guardian (CreateGuardianDto / UpdateGuardianDto plus the link's fields). */
export const guardianFormSchema = z.object({
  firstName: name("First name"),
  lastName: name("Last name"),
  relationship: z.enum(GUARDIAN_RELATIONSHIPS, { error: "Select a relationship" }),
  phone: requiredPhone,
  altPhone: optionalPhone,
  email: optionalEmail,
  addressLine: optionalText(255),
  occupation: optionalText(120),
  isPrimary: z.boolean(),
  canPickUp: z.boolean(),
});

export type GuardianFormValues = z.infer<typeof guardianFormSchema>;

/** Change Status: the reason is recorded on the audit entry. */
export const changeStatusSchema = z.object({
  status: z.enum(STUDENT_STATUSES),
  reason: optionalText(255),
});

export type ChangeStatusValues = z.infer<typeof changeStatusSchema>;

/**
 * Allergies and emergency contact have no backend field (agreed: keep them in notes).
 * Written as labelled lines so a person reading the notes later understands them.
 */
export function composeAdmissionNotes(v: Pick<AddStudentValues, "allergies" | "emergencyContactName" | "emergencyPhone">) {
  const lines: string[] = [];
  if (v.allergies) lines.push(`Allergies/conditions: ${v.allergies}`);
  if (v.emergencyContactName || v.emergencyPhone) {
    lines.push(`Emergency contact: ${[v.emergencyContactName, v.emergencyPhone].filter(Boolean).join(", ")}`);
  }
  return lines.length ? lines.join("\n") : null;
}
